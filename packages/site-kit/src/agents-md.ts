/**
 * `AGENTS.md` for a site repository (arch §2.3), generated from the schema and the block
 * registry so it is always accurate. Used by the starter, the CLI (`openspace agents-md`) and the
 * Hub when it creates a site.
 */
import { blocksRegistry } from "@openspace/blocks";
import { type BlockRegistry, type FieldMeta, SCHEMA_BASE_URL, schemaUrl } from "@openspace/schema";

export interface AgentsMdOptions {
  /** Block registry to document (default: the full library). */
  registry?: BlockRegistry;
  /** Site name for the heading. */
  siteTitle?: string;
}

function fieldSummary(name: string, m: FieldMeta): string {
  let type: string = m.kind;
  if (m.kind === "select") type = m.options.map((o) => `"${o.value}"`).join(" | ");
  else if (m.kind === "list")
    type = `list of { ${Object.entries(m.fields)
      .map(([k, f]) => fieldSummary(k, f))
      .join(", ")} }`;
  else if (m.kind === "text" && m.maxLength) type = `text ≤ ${m.maxLength}`;
  else if (m.kind === "image") type = "image { src, alt }";
  else if (m.kind === "link") type = "link";
  return `${name}${m.optional ? "?" : ""}: ${type}`;
}

/** Markdown for `AGENTS.md`. */
export function generateAgentsMd(opts: AgentsMdOptions = {}): string {
  const registry = opts.registry ?? blocksRegistry();
  const blocks = registry
    .list()
    .map((d) => d.meta)
    .sort((a, b) => a.type.localeCompare(b.type));
  const blockLines = blocks.map((b) => {
    const fields = Object.entries(b.fields)
      .map(([k, m]) => `\`${fieldSummary(k, m)}\``)
      .join(", ");
    return [
      `### \`${b.type}\` — ${b.label}`,
      "",
      `${b.ai.purpose} Use: ${b.ai.whenToUse} Avoid: ${b.ai.avoid}`,
      "",
      `- Variants: ${b.variants.map((v) => `\`${v}\``).join(", ") || "—"}`,
      `- Fields: ${fields || "—"}`,
      "",
    ].join("\n");
  });

  return `<!-- Generated by @openspace/site-kit from the schema and block registry. Do not edit by hand; run \`npx openspace agents-md\` to refresh. -->
# AGENTS.md — ${opts.siteTitle ?? "this OpenSpace site"}

This repository is an OpenSpace website. The content and design choices live here; the code
lives in versioned npm packages (\`@openspace/site-kit\`). Publishing happens automatically when
changes land on \`main\` (\`.github/workflows/publish.yml\`).

## Rules

1. **Content lives in \`content/\`.** Never hand-edit \`src/\`, \`astro.config.mjs\` or the
   workflow unless you were asked for a custom block (\`src/overrides/\`).
2. **Preserve ids.** Every page (\`pg_\`), section (\`sec_\`), block (\`blk_\`), media item (\`med_\`)
   and form (\`frm_\`) has a stable id. Keep ids when editing; new ids are the prefix plus 10
   lowercase Crockford base32 characters (no i, l, o, u).
3. **Only valid block types and fields** (listed below; full JSON Schema at
   ${SCHEMA_BASE_URL}/). Unknown fields fail the build.
4. **Styles change through tokens** in \`content/styles.json\` (palette, type pairing, density,
   shape…), never inline CSS. Sections pick one of five color themes.
5. **Never put secrets in content** (API keys, tokens, passwords). \`openspace check\` fails on them.
   Gated pages (members / password) are not stored in this repository.
6. **Run \`npx openspace check\` before committing.** It validates schemas, links, image references,
   size budgets and scans for secrets.
7. Write real copy in the owner's voice. No placeholder text, no invented testimonials, prices
   or facts — ask the owner.

## Layout

\`\`\`
openspace.json               site id, Hub URL, deploy target, features (${schemaUrl("site-config")})
content/site.json            title, navigation, header, footer, SEO defaults, redirects
content/styles.json          design tokens and Site Styles choices
content/media.json           metadata for files in media/ (alt text, size, focal point, credit)
content/pages/home.json      the home page (slug ""); other pages mirror their URL:
content/pages/about.json     → /about/      content/pages/services/pricing.json → /services/pricing/
content/collections/<name>/_collection.json   collection kind, list + item page layout, feeds
content/collections/<name>/<slug>.mdoc        one item: YAML frontmatter + Markdoc body
media/                       images ≤ 2400px on the long edge, audio, files
\`\`\`

A page is \`{ id, title, slug, seo?, sections: [...] }\`; a section has a \`layout\` (\`stack\` with
column spans that add up to 12, or \`grid\`) and \`blocks\`; a block is
\`{ id, type, v, fields, variant?, style? }\`.

## Collection items (Markdoc)

Frontmatter follows the collection kind (blog, events, portfolio, podcast, products): \`title\`,
\`status\` (draft | scheduled | published), \`publishAt\` for scheduled items, \`excerpt\`, \`image\`,
\`categories\`, \`tags\`, plus kind-specific fields (\`date\`, \`start\`/\`end\`, \`price\` in minor units…).

The body is Markdown prose plus Markdoc tags. **Tags map 1:1 to blocks**: the tag name is the
block type, attributes are its fields, and content between the tags fills its text:

\`\`\`markdoc
{% gallery layout="grid" images=["media/2026/10/a.jpg", "media/2026/10/b.jpg"] /%}

{% button href="/schedule" variant="primary" %}See the schedule{% /button %}
\`\`\`

No scripts or raw HTML: anything interactive is a block.

## Running locally

- \`npm install\`, then \`npm run dev\` for a live preview.
- \`npx openspace mcp\` starts the local MCP server so an AI assistant can edit through the same
  structured operations as the Studio.
- \`npm run build\` builds the site into \`dist/\` exactly as the publish workflow does.

## Blocks

${blockLines.join("\n")}`;
}
