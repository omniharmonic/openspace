// Regenerates src/templates/starter-files.ts from templates/starter (run: pnpm embed:starter).
// The Hub is a Worker without a filesystem, so the starter shell's text files are embedded.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const starter = join(here, "../../../templates/starter");

function walk(dir, base = dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const abs = join(dir, name);
    if (statSync(abs).isDirectory()) out.push(...walk(abs, base));
    else if (name !== ".gitkeep") out.push(relative(base, abs).split(sep).join("/"));
  }
  return out.sort();
}
const read = (dir) =>
  Object.fromEntries(walk(dir).map((p) => [p, readFileSync(join(dir, p), "utf8")]));

const site = read(join(starter, "site"));
const cloudflare = read(join(starter, "variants/cloudflare"));
const sitePkg = JSON.parse(site["package.json"]);
const cfPkg = JSON.parse(cloudflare["package.json"]);
const additions = {};
for (const section of ["dependencies", "devDependencies"])
  for (const [name, version] of Object.entries(cfPkg[section] ?? {}))
    if (!sitePkg[section]?.[name]) {
      additions[section] ??= {};
      additions[section][name] = version;
    }
const hosting = {
  "github-pages": {
    ".github/workflows/publish.yml": site[".github/workflows/publish.yml"],
    "astro.config.mjs": site["astro.config.mjs"],
  },
  cloudflare: {
    ".github/workflows/publish.yml": cloudflare[".github/workflows/publish.yml"],
    "astro.config.mjs": cloudflare["astro.config.mjs"],
    "wrangler.jsonc": cloudflare["wrangler.jsonc"],
  },
};

writeFileSync(
  join(here, "../src/templates/starter-files.ts"),
  `// biome-ignore-all lint/suspicious/noTemplateCurlyInString: GitHub Actions expressions in workflow files
// biome-ignore-all format: generated
/**
 * The starter shell (templates/starter), embedded so the Hub — a Worker without a filesystem —
 * can create sites from the template registry and switch their hosting. GENERATED by
 * scripts/embed-starter.mjs (\`pnpm embed:starter\`); test/hosting.test.ts checks it still matches.
 */

/** Every file of \`templates/starter/site\` (GitHub Pages shell), by repo path. */
export const STARTER_SITE_FILES: Readonly<Record<string, string>> = ${JSON.stringify(site, null, 2)};

/** The hosting-specific files per target. */
export const STARTER_HOSTING_FILES = ${JSON.stringify(hosting, null, 2)} as const;

/** package.json entries the Cloudflare variant adds to the shell's (merged, never overwritten). */
export const CLOUDFLARE_PACKAGE_ADDITIONS: Record<string, Record<string, string>> = ${JSON.stringify(additions, null, 2)};
`,
);
console.log("wrote src/templates/starter-files.ts");
