// Regenerates src/services/behavior-sources.ts (run: pnpm embed:behaviors). The Hub is a Worker
// without a filesystem, so the dev preview serves the renderer's behavior modules from here.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { bundleBehaviorSources } from "./behaviors-build.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const sources = await bundleBehaviorSources();
writeFileSync(
  join(here, "../src/services/behavior-sources.ts"),
  `// biome-ignore-all lint/suspicious/noTemplateCurlyInString: minified template literals
// biome-ignore-all format: generated
/**
 * The renderer's behavior modules (\`data-os-behavior\`), bundled and minified exactly like
 * \`@omniharmonic/openspace-renderer\`'s build. GENERATED by scripts/embed-behaviors.mjs
 * (\`pnpm embed:behaviors\`); test/preview.test.ts checks it is current.
 */
export const BEHAVIOR_SOURCES: Readonly<Record<string, string>> = ${JSON.stringify(sources, null, 2)};
`,
);
console.log(`wrote ${Object.keys(sources).length} behaviors`);
