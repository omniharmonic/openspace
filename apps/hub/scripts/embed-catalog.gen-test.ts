import { writeFileSync } from "node:fs";
import path from "node:path";
import { test } from "vitest";
import { computeLookPreviews } from "../src/services/look-preview";
import { computeTemplateCatalog, computeTemplateDocuments } from "../src/services/templates";

/**
 * Regenerates src/templates/catalog.ts and src/templates/documents.ts (run: `pnpm embed:catalog`, after `pnpm generate` in
 * templates/ or a theme change). test/templates-catalog.test.ts checks the embedded copy.
 */
test("embed the template catalog", async () => {
  const catalog = await computeTemplateCatalog();
  const previews = computeLookPreviews(catalog);
  writeFileSync(
    path.join(__dirname, "../src/templates/catalog.ts"),
    `// biome-ignore-all format: generated
/**
 * The template registry's gallery data, precomputed so a Worker never builds the twelve
 * templates (or compiles 36 looks' styles) to answer \`GET /api/templates\` or a site list.
 * GENERATED by scripts/embed-catalog.gen-test.ts (\`pnpm embed:catalog\`);
 * test/templates-catalog.test.ts checks it is current.
 */
import type { TemplateMeta } from "@omniharmonic/openspace-templates";
import type { LookPreview } from "../services/look-preview";

/** \`RegistryTemplateSource.list()\`: every launch template's gallery metadata, in gallery order. */
export const TEMPLATE_CATALOG: readonly TemplateMeta[] = ${JSON.stringify(catalog, null, 2)};

/** Each registry look's compact preview (\`lookPreview\`), keyed \`<template>/<look>\`. */
export const LOOK_PREVIEWS: Readonly<Record<string, LookPreview>> = ${JSON.stringify(previews, null, 2)};
`,
  );
  const documents = await computeTemplateDocuments();
  writeFileSync(
    path.join(__dirname, "../src/templates/documents.ts"),
    `// biome-ignore-all format: generated
/**
 * Each launch template's site document as JSON text — what \`GET /api/templates/:id\` serves —
 * so a Worker never builds a template to preview it in the gallery.
 * GENERATED by scripts/embed-catalog.gen-test.ts (\`pnpm embed:catalog\`);
 * test/templates-catalog.test.ts checks it is current.
 */
export const TEMPLATE_DOCUMENTS: Readonly<Record<string, string>> = ${JSON.stringify(documents, null, 2)};
`,
  );
});
